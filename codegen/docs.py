def field_doc(type_name: str, json_name: str) -> str | None:
    d = FIELDS.get(f"{type_name}.{json_name}") or FIELDS.get(json_name)
    if not d and type_name.endswith("Response"):
        return "The result. Client methods return this field directly."
    return d
