def connection_doc(name: str) -> str | None:
    if name.endswith("Connection"):
        node = name[: -len("Connection")]
        return f"One page of {node} results. Nodes() lists them; PageInfo says how to get the next page."
    if name.endswith("Edge"):
        node = name[: -len("Edge")]
        return f"Wraps one {node} in a page of results."
    return None


