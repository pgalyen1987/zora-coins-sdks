"""Emit the GraphQL gateway's schema and resolvers from the IR.

Outputs (all under graphql/):
  schema.graphql            the SDL, with every description — publish it, point codegen tools at it
  gateway/schema_gen.json   the same schema as data, which the server builds itself from at start
  gateway/resolvers_gen.go  one typed resolver per root field, each calling the Go SDK

Root fields mirror the SDK methods: `coin(address:)` is Client.Coin, `coinHolders(address:,
pageSize:, after:)` is Client.CoinHolders and returns a connection. Field names are the API's own
JSON names, so a GraphQL result decodes into the SDKs' existing types. `__typename` is reserved in
GraphQL, so Zora's own type name is exposed as `zoraType`.
"""

from __future__ import annotations

import json
import subprocess
import textwrap
from pathlib import Path

import docs
import ir as irmod
from emit_go import Go, go_arg, go_name, go_type_name
from emit_ts import camel

ROOT = Path(__file__).resolve().parent.parent / "graphql"
HEADER = "// Code generated by codegen/emit_graphql.py from Zora's OpenAPI spec. DO NOT EDIT.\n\n"
MUTATIONS = {"SetCreateUploadJWT"}  # issues a credential; everything else only reads or computes


def gql_field(json_name: str) -> str:
    return "zoraType" if json_name == "__typename" else json_name


def arg_name(op: irmod.Operation, p: irmod.Param) -> str:
    if p.name in ("chain", "chainId"):
        return "chainId"
    if op.page_size_param == p.name:
        return "pageSize"
    return p.name  # GraphQL arguments keep the API's camelCase (targetMarketCapUsd, not ...USD)


def gql_type(t: irmod.TypeRef, *, input_: bool = False) -> str:
    if t.kind == "list" and t.of:
        return f"[{gql_type(t.of, input_=input_)}!]"
    if t.kind == "scalar":
        return {"string": "String", "int": "Int", "float": "Float", "bool": "Boolean"}[t.name]
    if t.kind == "json":
        return "JSON"
    return t.name


def block(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    text = text.replace('"""', "'''")
    if len(text) < 90 and "\n" not in text:
        return f'{indent}"""{text}"""\n'
    body = "\n".join(indent + l for l in textwrap.wrap(text, 96))
    return f'{indent}"""\n{body}\n{indent}"""\n'


def build(model: irmod.IR) -> tuple[str, dict]:
    g = Go(model)
    sdl = ['"""\nThe Zora Coins API as one GraphQL schema: coins, profiles, holders, swaps, comments, Explore\n'
           'lists, search, leaderboards, live streams, trade quotes, coin creation, and onchain creator and\n'
           'referral rewards. Unofficial; not affiliated with Zora. Generated from Zora\'s OpenAPI spec.\n"""\n'
           "schema {\n  query: Query\n  mutation: Mutation\n}\n\n"]
    data: dict = {"enums": [], "objects": [], "inputs": [], "query": [], "mutation": []}
    returned: set[str] = set()

    def walk(name: str, seen: set[str]) -> None:
        if name in seen or name not in model.objects:
            return
        seen.add(name)
        for f in model.objects[name].fields:
            t = f.type.of if f.type.kind == "list" and f.type.of else f.type
            if t.kind == "object":
                walk(t.name, seen)

    roots = []
    for op in model.operations:
        meta = docs.METHODS[op.id]
        name = camel(meta["name"])  # GraphQL convention: createUploadJwt, not Go's createUploadJWT
        positional = [p for p in op.params if p.required and p.name not in ("chain", "chainId")]
        args = []
        for p in op.params:
            an = arg_name(op, p)
            if an == "pageSize" or an == "chainId" or p not in positional:
                t = "Int" if an in ("pageSize", "chainId") else gql_type(p.type, input_=True)
                req = False
            else:
                t, req = gql_type(p.type, input_=True), True
            args.append({"name": an, "type": t + ("!" if req else ""), "doc": docs.PARAMS.get(p.name) or p.description,
                         "param": p.name})
        if op.body:
            args.append({"name": "input", "type": op.body + "!", "doc": "The request.", "param": "__body"})
        if op.connection:
            ret = g._conn_type(op)
        elif op.unwrap:
            uf = next(f for f in model.objects[op.response].fields if f.json == op.unwrap)
            ret = gql_type(uf.type)
        else:
            ret = op.response
        base_ret = ret.strip("[]!")
        walk(base_ret, returned)
        doc = meta["doc"] + (" One page; pass pageInfo.endCursor as `after` for the next." if op.connection else "")
        roots.append({"op": op.id, "name": name, "args": args, "type": ret, "doc": doc, "mutation": op.id in MUTATIONS})

    # rewards: the one root field that isn't a REST call
    roots.append({"op": "__rewards", "name": "rewards", "type": "RewardsReport", "mutation": False,
                  "doc": "What addresses earned from Zora trading fees as creator, platform referrer or trade referrer, read "
                         "straight from Base (CoinMarketRewardsV4 events). Scans live, so keep `hours` small; USD uses current prices.",
                  "args": [{"name": "addresses", "type": "[String!]!", "doc": "Payout recipients or referrer addresses.", "param": "addresses"},
                           {"name": "hours", "type": "Float", "doc": "How far back to scan, up to 24. Defaults to 6.", "param": "hours"}]})

    for e in model.enums.values():
        sdl.append(block(docs.ENUM_DOCS.get(e.name)) + f"enum {e.name} {{\n" + "".join(f"  {v}\n" for v in e.values) + "}\n\n")
        data["enums"].append({"name": e.name, "values": e.values, "doc": docs.ENUM_DOCS.get(e.name)})

    inputs = sorted({n for n, o in model.objects.items() if o.input})
    for name, o in model.objects.items():
        if o.input:
            continue
        if name not in returned:
            continue
        doc = docs.TYPES.get(name) or docs.connection_doc(name)
        fields = []
        sdl.append(block(doc) + f"type {name} {{\n")
        for f in o.fields:
            fd = docs.field_doc(name, f.json) or f.description
            sdl.append(block(fd, "  ") + f"  {gql_field(f.json)}: {gql_type(f.type)}\n")
            fields.append({"name": gql_field(f.json), "json": f.json, "type": gql_type(f.type), "doc": fd})
        sdl.append("}\n\n")
        data["objects"].append({"name": name, "doc": doc, "fields": fields})
    for name in inputs:
        o = model.objects[name]
        fields = []
        sdl.append(block(docs.TYPES.get(name)) + f"input {name} {{\n")
        for f in o.fields:
            fd = docs.field_doc(name, f.json) or f.description or docs.PARAMS.get(f.json)
            t = gql_type(f.type, input_=True) + ("!" if f.required else "")
            sdl.append(block(fd, "  ") + f"  {f.json}: {t}\n")
            fields.append({"name": f.json, "json": f.json, "type": t, "doc": fd})
        sdl.append("}\n\n")
        data["inputs"].append({"name": name, "doc": docs.TYPES.get(name), "fields": fields})

    sdl.append(REWARDS_SDL)
    for kind, title in (("query", "Query"), ("mutation", "Mutation")):
        sdl.append(f"type {title} {{\n")
        for r in roots:
            if r["mutation"] != (kind == "mutation"):
                continue
            sdl.append(block(r["doc"], "  "))
            a = ""
            if r["args"]:
                a = "(\n" + "".join(block(x["doc"], "    ") + f"    {x['name']}: {x['type']}\n" for x in r["args"]) + "  )"
            sdl.append(f"  {r['name']}{a}: {r['type']}\n")
            data[kind].append(r)
        sdl.append("}\n\n")
    return "".join(sdl).rstrip() + "\n", data


REWARDS_SDL = '''"""What a set of addresses earned, per role and token, valued at current prices."""
type RewardsReport {
  addresses: [String!]
  """Reward events that paid any of the addresses."""
  events: Int
  fromBlock: Int
  toBlock: Int
  """Sum of every priced line, in USD at current prices."""
  totalUsd: Float
  lines: [RewardLine!]
}

"""What one role earned in one token."""
type RewardLine {
  """creator, platform_referrer, trade_referrer, protocol or doppler."""
  role: String
  """Token address (0x000… for native ETH)."""
  token: String
  symbol: String
  """Amount in the token's smallest unit, as an integer string."""
  raw: String
  """Amount in whole tokens."""
  amount: Float
  """Value at current prices; null when the token has no price."""
  usd: Float
  payouts: Int
}

'''


def qualify(go_type: str) -> str:
    """[]*CoinRefInput -> []*zora.CoinRefInput: the gateway lives outside package zora."""
    import re
    return re.sub(r"\b([A-Z]\w*)", r"zora.\1", go_type)


def resolvers(model: irmod.IR, data: dict) -> str:
    g = Go(model)
    out = [HEADER, 'package gateway\n\nimport (\n\t"context"\n\n\t"github.com/pgalyen1987/zora-coins-sdks/go/zora"\n)\n\n',
           "// callSDK runs the SDK method behind a root field. args has been decoded from the GraphQL\n"
           "// arguments by the caller; the result is returned as the SDK typed it.\n",
           "func callSDK(ctx context.Context, c *zora.Client, field string, args map[string]any) (any, error) {\n\tswitch field {\n"]
    by_id = {op.id: op for op in model.operations}
    for r in data["query"] + data["mutation"]:
        if r["op"] == "__rewards":
            continue
        op = by_id[r["op"]]
        m = go_name(docs.METHODS[op.id]["name"])
        positional = [p for p in op.params if p.required and p.name not in ("chain", "chainId")]
        optional = [p for p in op.params if p not in positional]
        out.append(f'\tcase "{r["name"]}":\n')
        call = ["ctx"]
        for p in positional:
            an = arg_name(op, p)
            gt = qualify(g.gtype(p.type, optional=False))
            if p.json_items:
                out.append(f"\t\tvar {an} {gt}\n\t\tif err := remarshal(args[\"{an}\"], &{an}); err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n")
                call.append(an)
            elif p.type.kind == "enum":
                call.append(f'{gt}(str(args["{an}"]))')
            else:
                call.append(f'str(args["{an}"])')
        if optional:
            fields = []
            for p in optional:
                fname, ft = g._param_field(op, p)
                an = arg_name(op, p)
                if ft == "int":
                    fields.append(f'{fname}: integer(args["{an}"])')
                elif ft == "string":
                    fields.append(f'{fname}: str(args["{an}"])')
                elif ft == "*bool":
                    fields.append(f'{fname}: boolPtr(args["{an}"])')
                elif p.type.kind == "enum":
                    fields.append(f'{fname}: {qualify(ft)}(str(args["{an}"]))')
                elif ft == "[]int":
                    fields.append(f'{fname}: ints(args["{an}"])')
                elif ft == "[]string":
                    fields.append(f'{fname}: strs(args["{an}"])')
                elif ft == "float64":
                    fields.append(f'{fname}: float(args["{an}"])')
                else:
                    raise ValueError(f"{op.id}.{p.name}: {ft}")
            call.append(f"&zora.{m}Params{{{', '.join(fields)}}}")
        if op.body:
            bt = go_type_name(op.body)
            out.append(f"\t\tvar body zora.{bt}\n\t\tif err := remarshal(args[\"input\"], &body); err != nil {{\n\t\t\treturn nil, err\n\t\t}}\n")
            call.append("&body")
        out.append(f"\t\treturn c.{m}({', '.join(call)})\n")
    out.append("\t}\n\treturn nil, errUnknownField(field)\n}\n")
    return "".join(out)


def main() -> None:
    model = irmod.build()
    sdl, data = build(model)
    (ROOT / "gateway").mkdir(parents=True, exist_ok=True)
    (ROOT / "schema.graphql").write_text(sdl)
    (ROOT / "gateway" / "schema.graphql").write_text(sdl)  # embedded by the server (Go can't embed from ../)
    (ROOT / "gateway" / "schema_gen.json").write_text(json.dumps(data, indent=1) + "\n")
    (ROOT / "gateway" / "resolvers_gen.go").write_text(resolvers(model, data))
    subprocess.run(["gofmt", "-w", str(ROOT / "gateway" / "resolvers_gen.go")], check=True)
    print(f"wrote graphql/schema.graphql ({len(data['objects'])} types, {len(data['inputs'])} inputs, "
          f"{len(data['query'])} queries, {len(data['mutation'])} mutations) and gateway/resolvers_gen.go")


if __name__ == "__main__":
    main()
