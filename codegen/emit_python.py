"""Emit the Python SDK's pydantic models from the IR (into the zora-coins-py repo).

Same types, names and documentation as the Go, Rust and GraphQL outputs. Field docs are attribute
docstrings, which pydantic turns into field descriptions and editors show on hover. The 0.1.0 model
names for response envelopes (GetCoinResponse, …) stay importable as aliases.
"""

from __future__ import annotations

import keyword
import re
import sys
import textwrap
from pathlib import Path

import docs
import ir as irmod
from emit_rust import snake

OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path.home() / "SAAS" / "zora-coins-py" / "src" / "zora_coins" / "_models.py"


def member(v: str) -> str:
    n = re.sub(r"[^0-9a-zA-Z]+", "_", v).strip("_").lower()
    if n[:1].isdigit():
        n = "v_" + n
    return n + "_" if keyword.iskeyword(n) else n


def old_member(v: str) -> str:
    """How 0.1.0 (datamodel-codegen) spelled an enum member: TOP_VOLUME_24H -> top_volume_24_h."""
    return re.sub(r"(\d)([a-z])", r"\1_\2", member(v))


def pyname(json_name: str) -> str:
    n = snake(json_name)
    return n + "_" if keyword.iskeyword(n) or n in ("model_config", "schema", "copy", "json", "dict") else n


def pytype(t: irmod.TypeRef) -> str:
    if t.kind == "list" and t.of:
        return f"list[{pytype(t.of)}]"
    if t.kind == "scalar":
        return {"string": "str", "int": "int", "float": "float", "bool": "bool"}[t.name]
    if t.kind == "json":
        return "Any"
    if t.kind == "enum":
        return f"{t.name} | str"  # a value Zora adds later still validates, as a plain string
    return t.name


def docstring(text: str | None, indent: str) -> str:
    if not text:
        return ""
    text = text.replace('"""', "'''").replace("\\", "\\\\")
    lines = textwrap.wrap(text, 100 - len(indent))
    if len(lines) == 1:
        return f'{indent}"""{lines[0]}"""\n'
    return f'{indent}"""' + ("\n" + indent).join(lines) + f'\n{indent}"""\n'


def main() -> None:
    model = irmod.build()
    out = ['# Code generated by zora-coins-sdks/codegen/emit_python.py from Zora\'s OpenAPI spec. DO NOT EDIT.\n'
           '"""Every type the Zora Coins API returns or accepts.\n\n'
           "Every response field is optional: the API returns a different selection of a coin's fields from each\n"
           "endpoint and leaves out some its own spec marks required. Enum fields also accept strings, so a value\n"
           'Zora adds later still validates.\n"""\n\n'
           "from __future__ import annotations\n\nfrom enum import Enum\nfrom typing import Any\n\n"
           "from pydantic import BaseModel, ConfigDict, Field\n\n\n"
           "class ZoraModel(BaseModel):\n"
           '    """Base of every model: fields by their Python name or the API\'s camelCase name, unknown fields kept."""\n\n'
           '    model_config = ConfigDict(populate_by_name=True, extra="allow", use_attribute_docstrings=True)\n\n\n']
    for e in model.enums.values():
        out.append(f"class {e.name}(str, Enum):\n")
        out.append(docstring(docs.ENUM_DOCS.get(e.name) or f"{e.name} values.", "    ") + "\n")
        for v in e.values:
            out.append(f'    {member(v)} = "{v}"\n')
        olds = [(v, old_member(v)) for v in e.values if old_member(v) != member(v)]
        if olds:
            out.append("    # 0.1.0 spellings, kept as aliases\n")
            out += [f'    {o} = "{v}"\n' for v, o in olds]
        out.append("\n\n")
    names = []
    for o in model.objects.values():
        names.append(o.name)
        d = docs.TYPES.get(o.name) or docs.connection_doc(o.name)
        if d:
            d = d.replace("Nodes() lists them", "nodes() lists them")
        if not d and o.name.endswith("Response"):
            d = "The raw response envelope. Client methods unwrap it."
        out.append(f"class {o.name}(ZoraModel):\n" + docstring(d or "A Zora API object.", "    ") + "\n")
        for f in o.fields:
            n = pyname(f.json)
            t = pytype(f.type)
            fd = docs.field_doc(o.name, f.json) or f.description or (docs.PARAMS.get(f.json) if o.input else None)
            alias = f', alias="{f.json}"' if n != f.json else ""
            if o.input and f.required:
                out.append(f"    {n}: {t} = Field(...{alias})\n")
            else:
                out.append(f"    {n}: {t} | None = Field(None{alias})\n")
            out.append(docstring(fd, "    "))
        if o.name.endswith("Connection") and any(f.json == "edges" for f in o.fields):
            edges = next(f for f in o.fields if f.json == "edges")
            edge = model.objects[edges.type.of.name]
            node = next((f for f in edge.fields if f.json == "node"), None)
            if node and node.type.kind == "object":
                out.append(f"\n    def nodes(self) -> list[{node.type.name}]:\n        \"\"\"The {node.type.name} values on this page, skipping empty edges.\"\"\"\n"
                           "        return [e.node for e in self.edges or [] if e is not None and e.node is not None]\n")
                out.append("\n    def next_cursor(self) -> str | None:\n        \"\"\"The cursor for the next page, or None on the last page.\"\"\"\n"
                           "        info = self.page_info\n        return info.end_cursor if info is not None and info.has_next_page else None\n")
        out.append("\n\n")
    out.append("for _m in (" + ", ".join(names) + "):\n    _m.model_rebuild()\n\n")
    # 0.1.0 names
    out.append("# Names from 0.1.0, kept so existing imports and type hints keep working.\n")
    for op in model.operations:
        old = op.id[0].upper() + op.id[1:] + "Response"
        if old != op.response:
            out.append(f"{old} = {op.response}\n")
    out.append("PostQuoteRequest = QuoteRequest\nPostCreateContentRequest = CreateContentCoinRequest\nSetCreateUploadJWTRequest = CreateUploadJwtRequest\n")
    out.append("ActivityType = SwapType\nType = TokenType\nType2 = MetadataType\nCurrency1 = ContentCoinCurrency\n\n\n")
    out.append('class ErrorType(str, Enum):\n    """Why a quote failed (the errorType of a 422 from /quote). See ZoraAPIError.error_type."""\n\n'
               '    liquidity = "LIQUIDITY"\n    unknown = "UNKNOWN"\n\n\n'
               'class Success(str, Enum):\n    """0.1.0 name: the success flag of a failed quote."""\n\n    false = "false"\n')
    OUT.write_text("".join(out))
    print(f"wrote {OUT}: {len(model.objects)} models, {len(model.enums)} enums")


if __name__ == "__main__":
    main()
