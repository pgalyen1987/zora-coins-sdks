"""Emit the Java SDK's generated sources from the IR: model classes, extensible enums, client methods."""

from __future__ import annotations

import html
import re
import shutil
import textwrap
from pathlib import Path

import docs
import ir as irmod
from emit_csharp import method_name as cs_method
from emit_go import Go, words

PKG = "io.github.pgalyen1987.zora"
ROOT = Path(__file__).resolve().parent.parent / "java" / "src" / "main" / "java" / "io" / "github" / "pgalyen1987" / "zora"
HEADER = "// Generated by codegen/emit_java.py from Zora's OpenAPI spec. Do not edit.\n"
_INIT = {"id": "Id", "url": "Url", "uri": "Uri", "usd": "Usd", "usdc": "Usdc", "jwt": "Jwt", "eth": "Eth"}
RESERVED = {"class", "default", "public", "private", "package", "import", "interface", "enum", "new", "type"}


def pascal(s: str) -> str:
    if s == "__typename":
        return "Typename"
    return "".join(_INIT.get(w.lower(), w[:1].upper() + (w[1:].lower() if w.isupper() and len(w) > 1 else w[1:])) for w in words(s))


def camel(s: str) -> str:
    p = pascal(s)
    n = p[:1].lower() + p[1:]
    return n + "_" if n in RESERVED else n


def const(v: str) -> str:
    """Java constant for an API value: TOP_VOLUME_24H stays TOP_VOLUME_24H, eth becomes ETH."""
    n = re.sub(r"[^0-9A-Za-z]+", "_", v).strip("_").upper()
    return ("V_" + n) if n[:1].isdigit() else n


def javadoc(text: str | None, indent: str = "    ") -> str:
    if not text:
        return ""
    lines = textwrap.wrap(html.escape(text, quote=False), 100 - len(indent))
    if len(lines) == 1:
        return f"{indent}/** {lines[0]} */\n"
    return f"{indent}/**\n" + "".join(f"{indent} * {l}\n" for l in lines) + f"{indent} */\n"


def jtype(t: irmod.TypeRef) -> str:
    if t.kind == "list" and t.of:
        return f"List<{jtype(t.of)}>"
    if t.kind == "scalar":
        return {"string": "String", "int": "Long", "float": "Double", "bool": "Boolean"}[t.name]
    if t.kind == "json":
        return "com.fasterxml.jackson.databind.JsonNode"
    return t.name


def jmethod(snake: str, *, iterate: bool = False) -> str:
    n = cs_method(snake)[:-5]  # GetCoin / Explore / Quote…, without Async
    if iterate:
        return "iterate" + n[3:] if n.startswith("Get") else "iterate" + n
    return n[:1].lower() + n[1:]


class Java:
    def __init__(self, model: irmod.IR) -> None:
        self.ir = model
        self.go = Go(model)

    def enum_file(self, e: irmod.EnumType) -> str:
        n = e.name
        d = (docs.ENUM_DOCS.get(n) or f"{n} values.") + " An extensible enum: values Zora adds later are kept, not rejected."
        consts = "".join(f'    /** {{@code {v}}} */\n    public static final {n} {const(v)} = new {n}("{v}");\n' for v in e.values)
        return (f"{HEADER}package {PKG}.model;\n\nimport com.fasterxml.jackson.annotation.JsonCreator;\nimport com.fasterxml.jackson.annotation.JsonValue;\n"
                f"import java.util.Arrays;\nimport java.util.Collections;\nimport java.util.List;\nimport java.util.Objects;\n\n"
                + javadoc(d, "") + f"public final class {n} {{\n{consts}\n"
                f"    /** Every value this SDK knows. */\n    public static final List<{n}> ALL = Collections.unmodifiableList(Arrays.asList({', '.join(const(v) for v in e.values)}));\n\n"
                f"    private final String value;\n\n    private {n}(String value) {{\n        this.value = Objects.requireNonNull(value);\n    }}\n\n"
                f"    /** Wraps any value, including ones this SDK doesn't know. */\n    @JsonCreator\n    public static {n} of(String value) {{\n"
                f"        for ({n} known : ALL) if (known.value.equals(value)) return known;\n        return new {n}(value);\n    }}\n\n"
                f"    /** The value as the API spells it. */\n    @JsonValue\n    public String value() {{\n        return value;\n    }}\n\n"
                f"    @Override\n    public boolean equals(Object o) {{\n        return o instanceof {n} && ((({n}) o).value).equals(value);\n    }}\n\n"
                f"    @Override\n    public int hashCode() {{\n        return value.hashCode();\n    }}\n\n"
                f"    @Override\n    public String toString() {{\n        return value;\n    }}\n}}\n")

    def model_file(self, o: irmod.ObjectType) -> str:
        d = docs.TYPES.get(o.name) or docs.connection_doc(o.name)
        if not d and o.name.endswith("Response"):
            d = "The raw response envelope. Client methods unwrap it."
        fields, accessors = [], []
        for f in o.fields:
            fd = docs.field_doc(o.name, f.json) or f.description or (docs.PARAMS.get(f.json) if o.input else None)
            required = o.input and f.required
            name = camel(f.json)
            prop = pascal(f.json)
            if f.json == "__typename":
                name = "typename"
            t = jtype(f.type)
            lenient = f.type.kind == "scalar" and f.type.format == "lenient"
            deser = "\n    @JsonDeserialize(using = FlexBooleanDeserializer.class)" if lenient else ""
            fields.append(f'    @JsonProperty("{f.json}"){deser}\n    private {t} {name};\n')
            doc = javadoc(((fd + " ") if fd else "") + ("Required." if required else "May be null: absent unless the endpoint selected it.") if not o.input else ((fd + " " if fd else "") + ("Required." if required else "Optional.")))
            accessors.append(doc + f"    public {t} get{prop}() {{\n        return {name};\n    }}\n\n")
            accessors.append(f"    /** Sets {{@link #get{prop}()}}. Returns this, for chaining. */\n    public {o.name} set{prop}({t} {name}) {{\n        this.{name} = {name};\n        return this;\n    }}\n\n")
        extra = ""
        if o.name.endswith("Connection") and any(f.json == "edges" for f in o.fields):
            edges = next(f for f in o.fields if f.json == "edges")
            edge = self.ir.objects[edges.type.of.name]
            node = next((f for f in edge.fields if f.json == "node"), None)
            if node and node.type.kind == "object":
                nt = node.type.name
                extra = (f"    /** The {nt} values on this page, skipping empty edges. */\n    public List<{nt}> nodes() {{\n"
                         f"        List<{nt}> out = new ArrayList<>();\n        if (edges != null) for ({edge.name} e : edges) if (e != null && e.getNode() != null) out.add(e.getNode());\n"
                         "        return out;\n    }\n\n"
                         "    /** The cursor for the next page, or null on the last page. */\n    public String nextCursor() {\n"
                         "        return pageInfo != null && Boolean.TRUE.equals(pageInfo.getHasNextPage()) ? pageInfo.getEndCursor() : null;\n    }\n\n")
        return (f"{HEADER}package {PKG}.model;\n\nimport com.fasterxml.jackson.annotation.JsonIgnoreProperties;\nimport com.fasterxml.jackson.annotation.JsonInclude;\n"
                f"import com.fasterxml.jackson.annotation.JsonProperty;\nimport com.fasterxml.jackson.databind.annotation.JsonDeserialize;\n"
                f"import io.github.pgalyen1987.zora.internal.FlexBooleanDeserializer;\nimport java.util.ArrayList;\nimport java.util.List;\n\n"
                + javadoc(d or "A Zora API object.", "")
                + f"@JsonIgnoreProperties(ignoreUnknown = true)\n@JsonInclude(JsonInclude.Include.NON_NULL)\npublic final class {o.name} {{\n"
                + "".join(fields) + "\n" + "".join(accessors) + extra + f"    @Override\n    public String toString() {{\n        return \"{o.name}\" + io.github.pgalyen1987.zora.internal.Json.toString(this);\n    }}\n}}\n")

    def _param_field(self, op: irmod.Operation, p: irmod.Param) -> tuple[str, str]:
        if p.name in ("chain", "chainId"):
            return "chainId", "Long"
        if op.page_size_param == p.name:
            return "pageSize", "Integer"
        return camel(p.name), jtype(p.type)

    def params_file(self, op: irmod.Operation, ptype: str, optional: list[irmod.Param], m: str) -> str:
        body = []
        for p in optional:
            fname, ft = self._param_field(op, p)
            body.append(f"    private {ft} {fname};\n")
        body.append("\n")
        for p in optional:
            fname, ft = self._param_field(op, p)
            up = fname[:1].upper() + fname[1:]
            body.append(javadoc(docs.PARAMS.get(p.name) or p.description))
            body.append(f"    public {ptype} {fname}({ft} {fname}) {{\n        this.{fname} = {fname};\n        return this;\n    }}\n\n")
            body.append(f"    /** The {fname} set, or null. */\n    public {ft} get{up}() {{\n        return {fname};\n    }}\n\n")
        body.append(f"    /** A copy, so pagination can move the cursor without touching the caller's object. */\n    public {ptype} copy() {{\n"
                    f"        {ptype} c = new {ptype}();\n" + "".join(f"        c.{self._param_field(op, p)[0]} = {self._param_field(op, p)[0]};\n" for p in optional)
                    + "        return c;\n    }\n")
        return (f"{HEADER}package {PKG};\n\nimport {PKG}.model.*;\nimport java.util.List;\n\n"
                + javadoc(f"Optional parameters of ZoraCoins.{m}. Unset values use the API's defaults.", "")
                + f"public final class {ptype} {{\n" + "".join(body) + "}\n")

    def client(self) -> tuple[str, dict[str, str]]:
        params_files: dict[str, str] = {}
        methods = []
        for op in self.ir.operations:
            meta = docs.METHODS[op.id]
            m = jmethod(meta["name"])
            ptype = "".join(x[:1].upper() + x[1:] for x in meta["name"].split("_")) + "Params"
            positional = [p for p in op.params if p.required and p.name not in ("chain", "chainId")]
            optional = [p for p in op.params if p not in positional]
            if optional:
                params_files[ptype] = self.params_file(op, ptype, optional, m)
            args = []
            for p in positional:
                t = jtype(p.type)
                args.append(f"{t if not p.json_items else 'List<' + p.type.of.name + '>'} {camel(p.name)}")
            if op.body:
                args.insert(0, f"{op.body} request")
            if op.connection:
                ret = ret_t = self.go._conn_type(op)
            elif op.unwrap:
                uf = next(f for f in self.ir.objects[op.response].fields if f.json == op.unwrap)
                ret_t = jtype(uf.type) if uf.type.kind == "list" else f"Optional<{jtype(uf.type)}>"
            else:
                ret_t = op.response
            d = meta["doc"]
            if op.connection:
                d += f" Returns one page; {jmethod(meta['name'], iterate=True)} walks every page."
            if meta.get("not_found"):
                d += " Empty if there is no such " + ("coin" if "coin" in m.lower() or "token" in m.lower() else "profile" if "profile" in m.lower() else "record") + "."
            sig_args = args + ([f"{ptype} params"] if optional else [])
            methods.append(javadoc(d + f" ({op.method} {op.path})"))
            methods.append(f"    public {ret_t} {m}({', '.join(sig_args)}) {{\n")
            if optional:
                methods.append(f"        {ptype} p = params == null ? new {ptype}() : params;\n")
            methods.append("        Query q = new Query();\n")
            for p in op.params:
                if p in positional:
                    a = camel(p.name)
                    if p.json_items:
                        methods.append(f'        for (Object item : {a}) q.add("{p.name}", Json.write(item));\n')
                    elif p.type.kind == "enum":
                        methods.append(f'        q.add("{p.name}", {a}.value());\n')
                    else:
                        methods.append(f'        q.add("{p.name}", {a});\n')
                else:
                    fname, ft = self._param_field(op, p)
                    getter = f"p.get{fname[:1].upper() + fname[1:]}()"
                    if fname == "chainId":
                        methods.append(f'        q.add("{p.name}", String.valueOf({getter} == null ? BASE_CHAIN_ID : {getter}));\n')
                    elif ft.startswith("List"):
                        methods.append(f'        if ({getter} != null) for (Object v : {getter}) q.add("{p.name}", Query.format(v));\n')
                    else:
                        methods.append(f'        if ({getter} != null) q.add("{p.name}", Query.format({getter}));\n')
            body = "request" if op.body else "null"
            methods.append(f'        {op.response} resp = send("{op.method}", "{op.path}", q, {body}, {op.response}.class);\n')
            if op.connection:
                # walk to the connection null-safely: resp.getZora20Token().getTokenBalances()…
                methods.append("        Object cur = resp;\n")
                t = op.response
                for k in op.connection:
                    f_ = next(x for x in self.ir.objects[t].fields if x.json == k)
                    methods.append(f"        cur = cur == null ? null : (({t}) cur).get{pascal(k)}();\n")
                    t = f_.type.name
                methods.append(f"        return cur == null ? new {ret}() : ({ret}) cur;\n    }}\n\n")
            elif op.unwrap:
                uf = next(f for f in self.ir.objects[op.response].fields if f.json == op.unwrap)
                if uf.type.kind == "list":
                    methods.append(f"        return resp == null || resp.get{pascal(op.unwrap)}() == null ? java.util.Collections.emptyList() : resp.get{pascal(op.unwrap)}();\n    }}\n\n")
                else:
                    methods.append(f"        return Optional.ofNullable(resp == null ? null : resp.get{pascal(op.unwrap)}());\n    }}\n\n")
            else:
                methods.append("        return resp;\n    }\n\n")
            if op.connection:
                node = op.node_type
                it = jmethod(meta["name"], iterate=True)
                names = [camel(p.name) for p in positional]
                methods.append(javadoc(f"Every {node} across all pages, fetched lazily as you iterate. Stop early with break. "
                                       "params.after picks the starting point."))
                methods.append(f"    public Iterable<{node}> {it}({', '.join(sig_args)}) {{\n")
                methods.append(f"        {ptype} start = params == null ? new {ptype}() : params.copy();\n")
                methods.append(f"        return () -> new Pages<>(start, p -> {{\n            {self.go._conn_type(op)} page = {m}({', '.join(names + ['p'])});\n"
                               f"            return new Pages.Page<>(page.nodes(), page.nextCursor());\n        }}, (p, cursor) -> p.after(cursor));\n    }}\n\n")
        client = (f"{HEADER}package {PKG};\n\nimport {PKG}.internal.Json;\nimport {PKG}.internal.Pages;\nimport {PKG}.internal.Query;\nimport {PKG}.model.*;\n"
                  "import java.util.List;\nimport java.util.Optional;\n\n"
                  "/** The endpoint methods, generated. Use {@link ZoraCoins}, which adds conveniences on top. */\n"
                  "abstract class GeneratedClient extends BaseClient {\n    GeneratedClient(Builder b) {\n        super(b);\n    }\n\n"
                  + "".join(methods).rstrip() + "\n}\n")
        return client, params_files


def main() -> None:
    model = irmod.build()
    j = Java(model)
    gen_model = ROOT / "model"
    if gen_model.exists():
        shutil.rmtree(gen_model)
    gen_model.mkdir(parents=True)
    for e in model.enums.values():
        (gen_model / f"{e.name}.java").write_text(j.enum_file(e))
    for o in model.objects.values():
        (gen_model / f"{o.name}.java").write_text(j.model_file(o))
    client, params = j.client()
    (ROOT / "GeneratedClient.java").write_text(client)
    for name, text in params.items():
        (ROOT / f"{name}.java").write_text(text)
    print(f"wrote java sources: {len(model.objects)} models, {len(model.enums)} enums, {len(params)} params classes, {len(model.operations)} endpoints")


if __name__ == "__main__":
    main()
