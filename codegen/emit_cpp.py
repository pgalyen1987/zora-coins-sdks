"""Emit the C++ SDK's generated headers from the IR: models (with JSON conversion) and client methods."""

from __future__ import annotations

import re
import textwrap
from pathlib import Path

import docs
import ir as irmod
from emit_go import Go
from emit_rust import Rust, field_ident as rust_field, snake, variant

OUT = Path(__file__).resolve().parent.parent / "cpp" / "include" / "zora"
HEADER = "// Generated by codegen/emit_cpp.py from Zora's OpenAPI spec. Do not edit.\n#pragma once\n\n"
KEYWORDS = set("""alignas alignof and and_eq asm auto bitand bitor bool break case catch char char8_t char16_t char32_t class
compl concept const consteval constexpr constinit const_cast continue co_await co_return co_yield decltype default delete do
double dynamic_cast else enum explicit export extern false float for friend goto if inline int long mutable namespace new
noexcept not not_eq nullptr operator or or_eq private protected public register reinterpret_cast requires return short signed
sizeof static static_assert static_cast struct switch template this thread_local throw true try typedef typeid typename union
unsigned using virtual void volatile wchar_t while xor xor_eq type""".split())  # plus "type", which reads badly unsuffixed next to type_ traits


def ident(json_name: str) -> str:
    n = snake(json_name)
    return n + "_" if n in KEYWORDS else n


def doc(text: str | None, indent: str = "") -> str:
    if not text:
        return ""
    return "".join(f"{indent}/// {l}\n" for l in textwrap.wrap(text, 100 - len(indent)))


class Cpp:
    def __init__(self, model: irmod.IR) -> None:
        self.ir = model
        self.go = Go(model)
        self.boxed, self.bare_lists = self._back_edges()

    def _back_edges(self) -> tuple[set[tuple[str, str]], set[tuple[str, str]]]:
        """Fields that close a cycle. C++ needs complete types for std::optional<T> and for
        std::optional<std::vector<T>>, so a cycle's closing object field becomes a shared_ptr and a
        closing list field a plain std::vector (empty = absent)."""
        boxed: set[tuple[str, str]] = set()
        bare: set[tuple[str, str]] = set()
        state: dict[str, int] = {}

        def visit(n: str) -> None:
            state[n] = 1
            for f in self.ir.objects[n].fields:
                is_list = f.type.kind == "list" and f.type.of is not None
                t = f.type.of if is_list else f.type
                if t.kind != "object":
                    continue
                if state.get(t.name) == 1:
                    (bare if is_list else boxed).add((n, f.json))
                elif t.name not in state:
                    visit(t.name)
            state[n] = 2

        for n in self.ir.objects:
            if n not in state:
                visit(n)
        return boxed, bare

    def ctype(self, t: irmod.TypeRef, owner: str = "", field: str = "") -> str:
        if t.kind == "list" and t.of:
            return f"std::vector<{self.ctype(t.of)}>"
        if t.kind == "scalar":
            return {"string": "std::string", "int": "std::int64_t", "float": "double", "bool": "bool"}[t.name]
        if t.kind == "json":
            return "nlohmann::json"
        if (owner, field) in self.boxed:
            return f"std::shared_ptr<{t.name}>"
        return t.name

    def order(self) -> list[str]:
        """Types in dependency order (by-value members first); boxed members only need a forward declaration."""
        done: list[str] = []
        seen: set[str] = set()

        def visit(n: str) -> None:
            if n in seen or n not in self.ir.objects:
                return
            seen.add(n)
            for f in self.ir.objects[n].fields:
                t = f.type.of if f.type.kind == "list" and f.type.of else f.type
                if t.kind == "object" and (n, f.json) not in self.boxed and (n, f.json) not in self.bare_lists:
                    visit(t.name)
            done.append(n)

        for n in self.ir.objects:
            visit(n)
        return done

    def models(self) -> str:
        out = [HEADER, "#include <cstdint>\n#include <memory>\n#include <optional>\n#include <string>\n#include <vector>\n\n"
               "#include <nlohmann/json.hpp>\n\n#include \"zora/json_util.hpp\"\n\n/// Every type the Zora Coins API returns or accepts. Response fields are std::optional: the API\n"
               "/// returns a different selection of a coin's fields from each endpoint.\nnamespace zora {\n\n"]
        for e in self.ir.enums.values():
            out.append(doc((docs.ENUM_DOCS.get(e.name) or f"{e.name} values.") + " Extensible: values Zora adds later are kept."))
            out.append(f"struct {e.name} {{\n    std::string value;\n")
            for v in e.values:
                out.append(f"    /// `{v}`\n    static const {e.name} {variant(v)};\n")
            out.append(f"    bool operator==(const {e.name}& o) const {{ return value == o.value; }}\n    bool operator!=(const {e.name}& o) const {{ return value != o.value; }}\n}};\n")
            for v in e.values:
                out.append(f'inline const {e.name} {e.name}::{variant(v)}{{"{v}"}};\n')
            out.append(f"inline void to_json(nlohmann::json& j, const {e.name}& e) {{ j = e.value; }}\n"
                       f"inline void from_json(const nlohmann::json& j, {e.name}& e) {{ e.value = j.get<std::string>(); }}\n\n")
        for n in self.ir.objects:
            out.append(f"struct {n};\n")
        out.append("\n")
        for n in self.order():
            o = self.ir.objects[n]
            d = docs.TYPES.get(n) or docs.connection_doc(n)
            if not d and n.endswith("Response"):
                d = "The raw response envelope. Client methods unwrap it."
            out.append(doc(d or "A Zora API object."))
            out.append(f"struct {n} {{\n")
            for f in o.fields:
                fd = docs.field_doc(n, f.json) or f.description or (docs.PARAMS.get(f.json) if o.input else None)
                required = o.input and f.required
                out.append(doc((fd + " Required.") if required and fd else ("Required." if required else fd), "    "))
                t = self.ctype(f.type, n, f.json)
                bare = (n, f.json) in self.boxed or (n, f.json) in self.bare_lists  # null / empty already mean absent
                out.append(f"    {t if required or bare else 'std::optional<' + t + '>'} {ident(f.json)};\n")
            if n.endswith("Connection") and any(f.json == "edges" for f in o.fields):
                edges = next(f for f in o.fields if f.json == "edges")
                edge = self.ir.objects[edges.type.of.name]
                node = next((f for f in edge.fields if f.json == "node"), None)
                if node and node.type.kind == "object":
                    out.append(f"\n    /// The {node.type.name} values on this page, skipping empty edges.\n    std::vector<{node.type.name}> nodes() const;\n"
                               "    /// The cursor for the next page, or empty on the last page.\n    std::string next_cursor() const;\n")
            out.append("};\n\n")
        # JSON conversion, after every type is complete
        for n in self.order():
            o = self.ir.objects[n]
            out.append(f"inline void from_json(const nlohmann::json& j, {n}& x) {{\n")
            for f in o.fields:
                required = o.input and f.required
                lenient = f.type.kind == "scalar" and f.type.format == "lenient"
                helper = "detail::get_flex_bool" if lenient else ("detail::get_required" if required else "detail::get_optional")
                out.append(f'    {helper}(j, "{f.json}", x.{ident(f.json)});\n')
            out.append("}\n")
            out.append(f"inline void to_json(nlohmann::json& j, const {n}& x) {{\n    j = nlohmann::json::object();\n")
            for f in o.fields:
                required = o.input and f.required
                out.append(f'    detail::{"put_required" if required else "put_optional"}(j, "{f.json}", x.{ident(f.json)});\n')
            out.append("}\n\n")
        # connection helpers
        for n in self.order():
            o = self.ir.objects[n]
            if n.endswith("Connection") and any(f.json == "edges" for f in o.fields):
                edges = next(f for f in o.fields if f.json == "edges")
                edge = self.ir.objects[edges.type.of.name]
                node = next((f for f in edge.fields if f.json == "node"), None)
                if node and node.type.kind == "object":
                    nt = node.type.name
                    out.append(f"inline std::vector<{nt}> {n}::nodes() const {{\n    std::vector<{nt}> out;\n"
                               f"    if (edges) for (const auto& e : *edges) if (e.node) out.push_back(*e.node);\n    return out;\n}}\n")
                    out.append(f"inline std::string {n}::next_cursor() const {{\n"
                               "    return page_info && page_info->has_next_page.value_or(false) && page_info->end_cursor ? *page_info->end_cursor : std::string();\n}\n\n")
        out.append("}  // namespace zora\n")
        return "".join(out)

    def _param_field(self, op: irmod.Operation, p: irmod.Param) -> tuple[str, str]:
        if p.name in ("chain", "chainId"):
            return "chain_id", "std::int64_t"
        if op.page_size_param == p.name:
            return "page_size", "int"
        return ident(p.name), self.ctype(p.type)

    def client(self) -> str:
        decl, impl, params = [], [], []
        for op in self.ir.operations:
            meta = docs.METHODS[op.id]
            m = meta["name"]
            ptype = "".join(x[:1].upper() + x[1:] for x in m.split("_")) + "Params"
            positional = [p for p in op.params if p.required and p.name not in ("chain", "chainId")]
            optional = [p for p in op.params if p not in positional]
            if optional:
                params.append(doc(f"Optional parameters of Client::{m}. Unset values use the API's defaults."))
                params.append(f"struct {ptype} {{\n")
                for p in optional:
                    fname, ft = self._param_field(op, p)
                    params.append(doc(docs.PARAMS.get(p.name) or p.description, "    "))
                    params.append(f"    std::optional<{ft}> {fname};\n")
                params.append("};\n\n")
            args = []
            for p in positional:
                t = self.ctype(p.type)
                args.append(f"const {t}& {ident(p.name)}")
            if op.body:
                args.insert(0, f"const {op.body}& request")
            if optional:
                args.append(f"const {ptype}& params = {{}}")
            if op.connection:
                ret = self.go._conn_type(op)
                ret_t = ret
            elif op.unwrap:
                uf = next(f for f in self.ir.objects[op.response].fields if f.json == op.unwrap)
                ret_t = self.ctype(uf.type) if uf.type.kind == "list" else f"std::optional<{self.ctype(uf.type)}>"
            else:
                ret_t = op.response
            d = meta["doc"]
            if op.connection:
                d += f" Returns one page; for_each_{m} walks every page."
            if meta.get("not_found"):
                d += " Empty if there is no such " + ("coin" if "coin" in m or "token" in m else "profile" if "profile" in m else "record") + "."
            decl.append(doc(d + f" ({op.method} {op.path})", "    ") + f"    {ret_t} {m}({', '.join(args)});\n")
            ia = [a.replace(" = {}", "") for a in args]
            body = [f"inline {ret_t} Client::{m}({', '.join(ia)}) {{\n    detail::Query q;\n"]
            for p in op.params:
                if p in positional:
                    a = ident(p.name)
                    if p.json_items:
                        body.append(f'    for (const auto& item : {a}) q.add("{p.name}", nlohmann::json(item).dump());\n')
                    elif p.type.kind == "enum":
                        body.append(f'    q.add("{p.name}", {a}.value);\n')
                    else:
                        body.append(f'    q.add("{p.name}", {a});\n')
                else:
                    fname, ft = self._param_field(op, p)
                    if fname == "chain_id":
                        body.append(f'    q.add("{p.name}", std::to_string(params.chain_id.value_or(kBaseChainId)));\n')
                    elif ft.startswith("std::vector"):
                        body.append(f'    if (params.{fname}) for (const auto& v : *params.{fname}) q.add("{p.name}", detail::format(v));\n')
                    else:
                        body.append(f'    if (params.{fname}) q.add("{p.name}", detail::format(*params.{fname}));\n')
            payload = "nlohmann::json(request).dump()" if op.body else "std::string()"
            body.append(f'    auto resp = send<{op.response}>("{op.method}", "{op.path}", q, {payload});\n')
            if op.connection:
                expr = "resp"
                t = op.response
                steps = []
                for k in op.connection:
                    f_ = next(x for x in self.ir.objects[t].fields if x.json == k)
                    boxed = (t, k) in self.boxed
                    steps.append((ident(k), boxed))
                    t = f_.type.name
                # walk the optionals (and shared_ptrs) down to the connection
                body.append(f"    const auto* cur0 = &resp;\n")
                prev = "cur0"
                for i, (k, boxed) in enumerate(steps, 1):
                    body.append(f"    if (!{prev}->{k}) return {{}};\n")
                    body.append(f"    const auto* cur{i} = " + (f"{prev}->{k}.get()" if boxed else f"&*{prev}->{k}") + ";\n")
                    prev = f"cur{i}"
                body.append(f"    return *{prev};\n}}\n\n")
            elif op.unwrap:
                uf = next(f for f in self.ir.objects[op.response].fields if f.json == op.unwrap)
                if uf.type.kind == "list":
                    body.append(f"    return resp.{ident(op.unwrap)}.value_or({ret_t}{{}});\n}}\n\n")
                else:
                    body.append(f"    return resp.{ident(op.unwrap)};\n}}\n\n")
            else:
                body.append("    return resp;\n}\n\n")
            impl.append("".join(body))
            if op.connection:
                node = op.node_type
                fa = [a for a in args if not a.startswith(f"const {ptype}&")] + [f"const {ptype}& params", f"const std::function<bool(const {node}&)>& visit"]
                decl.append(doc(f"Calls visit for every {node} across all pages, fetching each page as needed. Return false from "
                                "visit to stop. params.after picks the starting point.", "    ") + f"    void for_each_{m}({', '.join(fa)});\n")
                call = ", ".join([ident(p.name) for p in positional] + ["p"])
                impl.append(f"inline void Client::for_each_{m}({', '.join(fa)}) {{\n    {ptype} p = params;\n    std::set<std::string> seen;\n"
                            f"    for (;;) {{\n        auto page = {m}({call});\n        for (const auto& n : page.nodes()) if (!visit(n)) return;\n"
                            "        auto next = page.next_cursor();\n        if (next.empty() || !seen.insert(next).second) return;\n        p.after = next;\n    }\n}\n\n")
        return "".join(params), "".join(decl), "".join(impl)


def main() -> None:
    model = irmod.build()
    c = Cpp(model)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "models.hpp").write_text(c.models())
    params, decl, impl = c.client()
    (OUT / "endpoints.hpp").write_text(HEADER + "#include <functional>\n#include <set>\n\n#include \"zora/models.hpp\"\n\nnamespace zora {\n\n" + params + "}  // namespace zora\n")
    (OUT / "client_methods.inc").write_text("// Generated by codegen/emit_cpp.py. Included inside class zora::Client.\n" + decl)
    (OUT / "client_impl.inc").write_text("// Generated by codegen/emit_cpp.py. Method bodies of zora::Client.\n" + impl)
    print(f"wrote cpp/include/zora headers: {len(model.objects)} types, {len(model.enums)} enums, {len(model.operations)} endpoints; shared_ptr fields: {len(c.boxed)}")


if __name__ == "__main__":
    main()
